function createLesson(seed: LessonSeed): Lesson {
  const languageName =
    seed.languageId === "spanish" ? "Spanish" : seed.languageId === "french" ? "French" : "Japanese";

  return {
    id: seed.id,
    languageId: seed.languageId,
    unitId: seed.unitId,
    title: seed.title,
    subtitle: seed.subtitle,
    kind: seed.kind,
    order: seed.order,
    xpReward: seed.kind === "review" ? 20 : 10,
    estimatedMinutes: seed.kind === "review" ? 8 : 5,
    difficulty: seed.order <= 2 ? "beginner" : "easy",
    goals: [
      { id: `${seed.id}-goal-1`, label: `Understand ${seed.focus}.` },
      { id: `${seed.id}-goal-2`, label: `Say "${seed.phrase}" out loud.` },
    ],
    vocabulary: [
      {
        id: `${seed.id}-vocab-1`,
        term: seed.term,
        translation: seed.translation,
        pronunciation: seed.pronunciation,
        example: seed.phrase,
      },
    ],
    phrases: [
      {
        id: `${seed.id}-phrase-1`,
        text: seed.phrase,
        translation: seed.phraseTranslation,
        pronunciation: seed.phrasePronunciation,
        context: seed.focus,
      },
    ],
    activities: starterActivities(
      languageName,
      seed.term,
      seed.translation,
      seed.phrase,
      seed.phraseTranslation,
    ),
    aiTeacherPrompt: {
      persona: `You are a warm ${languageName} teacher for absolute beginners.`,
      lessonBrief: `Teach ${seed.focus} using one clear example at a time.`,
      speakingCue: `Ask the learner to repeat "${seed.phrase}" slowly, then naturally.`,
      correctionStyle: "Correct pronunciation gently and celebrate small wins.",
    },
  };
}

export const lessons: Lesson[] = lessonSeeds.map(createLesson);

export function getLessonsByLanguage(languageId: LanguageId) {
  return lessons
    .filter((lesson) => lesson.languageId === languageId)
    .sort((firstLesson, secondLesson) => firstLesson.order - secondLesson.order);
}

export function getLessonsByUnit(unitId: string) {
  return lessons
    .filter((lesson) => lesson.unitId === unitId)
    .sort((firstLesson, secondLesson) => firstLesson.order - secondLesson.order);
}

export function getLessonById(lessonId: string) {
  return lessons.find((lesson) => lesson.id === lessonId);
}
